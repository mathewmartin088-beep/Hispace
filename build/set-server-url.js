// Bakes the central server address into the desktop app:  SERVER_URL=https://chat.example.com npm run dist
const fs = require('fs');
const path = require('path');
const url = (process.env.SERVER_URL || '').trim().replace(/\/+$/, '');
if (url && !/^https?:\/\//i.test(url)) { console.error('SERVER_URL must start with http:// or https://'); process.exit(1); }
const file = path.join(__dirname, '..', 'public', 'config.js');
fs.writeFileSync(file, '// Generated by build/set-server-url.js\nwindow.HISPACE_CONFIG = { serverUrl: ' + JSON.stringify(url) + ' };\n');
console.log(url ? 'Server address set to ' + url : 'No SERVER_URL given: the app will ask for the server address on first run.');
